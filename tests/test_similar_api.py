PATH = "/v1/recommendations/similar"


def request():
    rows = (
        (10, "reference", "authored beer", ["authored dry"], 1000, 5, 330, True),
        (11, "reference", "authored beer", ["authored dry"], 1000, 5, 330, True),
        (20, "other-a", "authored beer", ["authored dry"], 1000, 5, 330, True),
        (30, "other-b", "authored wine", ["authored sweet"], 1000, 12, 750, True),
        (40, "other-c", None, None, 1000, None, None, True),
        (50, "other-d", "authored beer", ["authored dry"], None, 5, 330, True),
        (60, "other-e", "authored beer", ["authored dry"], 1000, 5, 330, False),
        (70, "other-f", "authored beer", ["authored dry"], 1000, 5, 330, True),
        (80, "other-g", "authored beer", None, 1000, 0, None, True),
    )
    return {
        "catalog": [
            dict(
                product_id=pid,
                sku_group=group,
                category=category,
                taste_tags=taste,
                price_krw=price,
                abv_percent=abv,
                volume_ml=volume,
                available=available,
            )
            for pid, group, category, taste, price, abv, volume, available in rows
        ],
        "reference_product_id": 10,
        "constraints": {
            "exclude_product_ids": [70],
            "min_price_krw": 500,
            "max_price_krw": 1500,
            "max_abv_percent": 8,
        },
        "limit": 10,
    }


def execute(value):
    return recommend_similar(SimilarRecommendationRequest.model_validate(value))


def test_reference_variants_and_hard_failures_never_fill_similar_items():
    value = request()
    original = copy.deepcopy(value)
    result = execute(value)
    # Declared facts, not expected labels generated by a production scoring/filter helper.
    assert [item.product_id for item in result.items] == [20, 80]
    assert result.eligible_count == 2 and result.excluded_reference_group_count == 2
    assert result.reference_state == "available" and result.reference_product_id == 10
    assert result.reference_sku_group == "reference"
    assert result.profile_source == "reference_product_facts"
    assert result.reference_group_policy == "exclude_reference_group"
    assert result.fallback_reason is None and result.representation_fitted
    assert value == original
    # Reuse evidence is separate from the independently declared candidate facts above.
    products = [ContentProduct.model_validate(row) for row in value["catalog"]]
    model = FittedContentModel.fit(products)
    before = model.similar(
        products[0],
        [p for p in products if p.sku_group != "reference"],
        SimilarRecommendationRequest.model_validate(value).constraints,
        limit=value["limit"],
    )
    assert result.items == before.items
    assert result.model_fingerprint == before.model_fingerprint
    for item in result.items:
        assert item.score > 0
        assert item.score == pytest.approx(sum(p.contribution for p in item.contributions))
        assert "content_similarity" in item.reasons


def test_soft_reference_category_does_not_become_a_hard_constraint():
    value = request()
    value["constraints"] = {"categories": ["authored wine"]}
    result = execute(value)
    assert [item.product_id for item in result.items] == [30]
    assert result.items[0].contributions
    assert all(p.component != "text" for p in result.items[0].contributions)


def test_unknown_numeric_does_not_pass_a_required_zero_and_unrelated_zero_is_not_fill():
    value = request()
    value["constraints"] = {"max_abv_percent": 0}
    result = execute(value)
    assert [item.product_id for item in result.items] == [80]
    assert result.eligible_count == 1
    value["constraints"] = {"exclude_product_ids": [50, 60, 70]}
    result = execute(value)
    assert result.eligible_count == 4  # Known hard candidates include the all-unknown item.
    assert 40 not in [item.product_id for item in result.items]
    assert all(item.score > 0 for item in result.items)


@pytest.mark.parametrize("mode", ["empty", "missing", "unavailable"])
def test_unusable_reference_has_explicit_empty_fallback_without_fit(mode, monkeypatch):
    value = request()
    if mode == "empty":
        value["catalog"] = []
    elif mode == "missing":
        value["reference_product_id"] = 999
    else:
        value["catalog"][0]["available"] = False

    def forbidden(_):
        raise AssertionError("No numerical fit for an unusable reference")

    monkeypatch.setattr(FittedContentModel, "fit", forbidden)
    result = execute(value)
    assert result.items == [] and result.eligible_count is None
    assert result.excluded_reference_group_count is None
    assert not result.representation_fitted and result.model_fingerprint is None
    assert result.fallback_reason == (
        "reference_unavailable" if mode == "unavailable" else "reference_not_in_catalog"
    )
    assert result.reference_state == ("unavailable" if mode == "unavailable" else "missing")
    assert result.reference_sku_group == ("reference" if mode == "unavailable" else None)


@pytest.mark.parametrize("mode", ["empty-candidates", "unknown-reference", "no-overlap"])
def test_missing_candidate_or_reference_evidence_never_becomes_fake_similarity(mode):
    value = {
        "catalog": [
            {"product_id": 1, "sku_group": "a", "available": True, "category": "one"},
            {"product_id": 2, "sku_group": "b", "available": True, "category": "two"},
        ],
        "reference_product_id": 1,
    }
    if mode == "empty-candidates":
        value["catalog"][1]["sku_group"] = "a"
    elif mode == "unknown-reference":
        value["catalog"][0]["category"] = None
    result = execute(value)
    assert result.items == []
    assert (
        result.fallback_reason
        == {
            "empty-candidates": "no_eligible_products",
            "unknown-reference": "no_supported_preferences",
            "no-overlap": "no_matching_features",
        }[mode]
    )
    assert result.eligible_count == (0 if mode == "empty-candidates" else 1)


def test_nonempty_constant_unknown_representation_is_not_usable_fit():
    result = execute(
        {
            "catalog": [
                {"product_id": i, "sku_group": str(i), "available": True, "abv_percent": 5}
                for i in (1, 2)
            ],
            "reference_product_id": 1,
        }
    )
    assert not result.representation_fitted and result.model_fingerprint is None
    assert result.items == [] and result.fallback_reason == "no_supported_preferences"


def test_internal_group_removal_does_not_consume_the_callers_exclusion_budget():
    value = request()
    value["constraints"]["exclude_product_ids"] = list(range(1000, 2000))
    result = execute(value)
    assert result.excluded_reference_group_count == 2
    assert 10 not in [item.product_id for item in result.items]
    assert 11 not in [item.product_id for item in result.items]


def test_permutations_and_concurrent_different_references_do_not_share_state():
    value = request()
    expected = execute(value)
    value["catalog"].reverse()
    assert execute(value) == expected
    other = copy.deepcopy(value)
    other["reference_product_id"] = 30
    other["constraints"] = {}
    with ThreadPoolExecutor(max_workers=2) as pool:
        actual, other_result = list(pool.map(execute, [value, other]))
    assert actual == expected and other_result.reference_product_id == 30
    assert all(item.product_id != 30 for item in other_result.items)
    assert execute(value) == expected


@pytest.mark.parametrize(
    "change",
    ["id-string", "id-bool", "id-zero", "id-large", "duplicate-id", "limit-bool", "extra"],
)
def test_strict_reference_existing_catalog_and_limit_bounds(change):
    value = request()
    if change.startswith("id-"):
        value["reference_product_id"] = {
            "id-string": "10",
            "id-bool": True,
            "id-zero": 0,
            "id-large": 2_147_483_648,
        }[change]
    elif change == "duplicate-id":
        value["catalog"].append(copy.deepcopy(value["catalog"][0]))
    elif change == "limit-bool":
        value["limit"] = True
    else:
        value["profile"] = {"categories": ["not a reference fact"]}
    with pytest.raises(ValidationError):
        SimilarRecommendationRequest.model_validate(value)


def test_http_and_openapi_expose_reference_source_and_uncomputed_eligibility():
    with TestClient(app) as client:
        value = request()
        result = client.post(PATH, json=value)
        assert result.status_code == 200 and result.json() == execute(value).model_dump()
        cold = client.post(PATH, json={"catalog": [], "reference_product_id": 1})
        assert cold.status_code == 200 and cold.json()["eligible_count"] is None
        invalid = client.post(PATH, json={"catalog": [], "reference_product_id": "PRIVATE"})
        assert invalid.status_code == 422 and "PRIVATE" not in invalid.text
        assert all(set(error) == {"type", "loc", "msg"} for error in invalid.json()["detail"])
        schema = client.get("/openapi.json").json()
        assert set(schema["paths"][PATH]["post"]["responses"]) >= {"200", "408", "413", "422"}


@pytest.mark.parametrize("media", ["application/json", "application/vnd.pubburi+json", None])
@pytest.mark.parametrize("root_path", ["", "/internal/recommendation"])
def test_raw_key_ambiguity_and_original_malformed_priority_are_preserved(media, root_path):
    headers = {} if media is None else {"Content-Type": media}
    path = root_path + PATH
    with TestClient(app, root_path=root_path) as client:
        response = client.post(
            path,
            content='{"catalog":[],"reference_product_id":1,"reference_product_\\u0069d":1}',
            headers=headers,
        )
        assert response.status_code == 422
        assert response.json()["detail"][0]["type"] == "duplicate_json_key"
        invalid = '{"catalog":[],"catalog":[]} trailing'
        response = client.post(path, content=invalid, headers=headers)
        existing = client.post(
            root_path + "/v1/recommendations/content", content=invalid, headers=headers
        )
        assert response.status_code == existing.status_code == 422
        assert response.json() == existing.json()
        error_type = response.json()["detail"][0]["type"]
        assert error_type != "duplicate_json_key"
        if media is not None:
            assert error_type == "json_invalid"
        assert client.post(path, content=b" " * 524289, headers=headers).status_code == 413


